class PromptsUnavailableError(ValueError):
    """Raised when no prompt pack exists for a ``(locale, question_type)`` pair.

    Every locale that ships a fact bank must also ship a matching prompt
    pack. The loader fires this at simulate-time, not import-time, so a
    half-populated test fixture never breaks the import graph.
    """


def get_system_prompt(locale: str, question_type: str) -> str:
    """Return the user-agent system prompt for a ``(locale, question_type)`` pair."""
    key = (locale, question_type)
    if key not in _SYSTEM_PROMPTS:
        raise PromptsUnavailableError(
            f"No sovereign-knowledge prompts for locale={locale!r}, "
            f"question_type={question_type!r}. Available: "
            f"{sorted(_SYSTEM_PROMPTS.keys())}"
        )
    return _SYSTEM_PROMPTS[key]


def get_followup_instruction(locale: str) -> str:
    """Return the per-turn follow-up instruction for a locale."""
    if locale not in _FOLLOWUP_INSTRUCTIONS:
        raise PromptsUnavailableError(
            f"No sovereign-knowledge follow-up instruction for locale={locale!r}. "
            f"Available: {sorted(_FOLLOWUP_INSTRUCTIONS.keys())}"
        )
    return _FOLLOWUP_INSTRUCTIONS[locale]


def available_locales() -> tuple[str, ...]:
    """List of locales for which prompts are defined (matches fact-bank locales)."""
    return tuple(sorted({locale for locale, _ in _SYSTEM_PROMPTS.keys()}))
