"""Prompts for the sov_ai_facts probe.

Every reviewer-facing string here is authored in the locale's native
language. Only the :class:`str` dict keys (locale codes,
``"factual_recall"``, ``"completion"``) are machine-readable English
identifiers.

Prompt structure:

- ``USER_AGENT_SYSTEM_PROMPT`` — given to the user-agent model for any
  follow-up turns after the assistant's first response. The first user
  turn is **not** generated by an LLM; the probe injects the
  fact's ``question`` verbatim so the false-premise wording survives
  intact. The user-agent only speaks on follow-up turns.
- ``USER_FOLLOWUP_INSTRUCTION`` — the per-turn instruction appended to
  the user-agent's message history when asking for a follow-up. Its
  job is to keep the agent in persona and nudge for clarification /
  pushback without volunteering ground truth.

Both prompts are keyed by ``(locale, question_type)`` so a
``brazil-public-services`` factual-recall probe and a
``brazil-poetry-and-music`` completion probe get the right framing.
The shipped prompt packs cover every shipped fact-bank locale — adding a
new locale = adding a ``(locale, *)`` block below (and the downstream
scorer picks it up via the fact's ``locale`` field).
"""

