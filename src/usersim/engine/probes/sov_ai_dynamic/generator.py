"""sov_ai_dynamic probe.

Probes the assistant for locale-specific topical breadth using a
per-locale category taxonomy. Structurally inverse of ``sov_ai_facts``:
there is **no curated question** to inject verbatim — turn 1 is
generated by the user-LLM in the persona's voice, anchored to one
``(category, subtopic_hint)`` pair from the taxonomy. The standard
user-judge gate fires on the generated turn-1.

Built on ``BaseProbe`` + ``BankBackedProbe``; the substrate handles
taxonomy load + cache + placeholder warning +
``provenance.bank_version[locale]`` pinning. ``ConversationLoop``
drives the turn loop with shared guardrails (fourth-wall prefilter,
user-judge gate retries, role-violation telemetry, frustration).

Note on shape: this probe does NOT use ``BankVerbatimMixin`` because
turn-1 is generated. The taxonomy-templated opening (persona +
invitation + subtopic_hint) is supplied via ``get_user_system_prompt``
— the user-LLM gets all context in the system message, then the
standard ``USER_QUERY_INSTRUCTION`` triggers turn-1 generation. The
plan's reference to ``CustomTurn1InstructionMixin`` was a guideline;
the actual probe doesn't need it because the existing prompt design
already carries persona + topic context in a single system message
(splitting across system + user-instruction would change behavior
without measurable benefit).

Side channels emitted on the trajectory:

- ``state.metadata["probing_categories_explored"]`` — list of
  category ids probed (today always ``[category.id]``).
- ``state.metadata["probing_subtopic_hints_used"]`` — list of
  sub-topic hint strings.
- ``state.metadata["taxonomy_id"]`` / ``taxonomy_version`` — for
  scorer reload + reporter stratification.
- ``result["probe_variant"]`` = ``category.id`` (per-row discriminator).
- ``result["probing_categories_explored"]`` /
  ``result["probing_subtopic_hints_used"]`` — top-level columns the
  scorer reads.
- ``SimulationOutcome.provenance.bank_version["<locale>"]`` —
  taxonomy version (locale-keyed; ``BankBackedProbe`` substrate
  handles via ``bank_version_key=None``).
- ``SimulationOutcome.warnings`` —
  ``WarningKind.USED_PLACEHOLDER_TAXONOMY`` appended whenever the
  taxonomy carried ``placeholder: true`` (substrate-driven).
"""

