"""Prompts for the sov_ai_multilingual_parity probe.

Every reviewer-facing string here is authored in the locale's native
language. Only the :class:`str` dict keys (``"pt_BR"``, ``"ja_JP"``,
``"hi_Deva_IN"``, …) are machine-readable English identifiers.

Prompt structure mirrors the sov_ai_facts probe:

- ``USER_AGENT_SYSTEM_PROMPT`` — given to the user-agent model for any
  follow-up turns after the assistant's first response. The first user
  turn is **not** generated by an LLM; the probe injects the
  query's locale-specific rendering verbatim so cross-locale matched-
  pair comparison sees the exact authored text.
- ``USER_FOLLOWUP_INSTRUCTION`` — the per-turn instruction appended to
  the user-agent's message history when asking for a follow-up.

This probe ships every supported locale because
matched-pair cross-locale comparison is its load-bearing semantic:
shipping with missing locales would silently exclude them
from every matched-pair pool. Authored as placeholder reviewer-quality
content (functional, but a native reviewer pass would tighten idiom);
the locale-content audit lives in the same reviewer queue as the
``sov_ai_multilingual_parity`` query bank itself.
"""

